# -*- coding: utf-8 -*-
"""Builds the legal entry pages (the index.html that stores, apps and Google link to) from the English documents.

Every entry URL shows the full English document text directly, never only a language chooser or a redirect
(Google OAuth brand review 2026-10: a chooser page was judged "not sufficient content"). Each copy gets a canonical
link to the English page, keeps the document's own language links, and moves people with JavaScript to the Korean /
German document when their browser lists that language before English (ja and everyone else stay on English).

  python3 scripts/build_legal_entry_pages.py          # rewrite the entry pages
  python3 scripts/build_legal_entry_pages.py --check  # exit 1 when an entry page is out of date with its source

Edit the English source document, never the generated index.html.
"""
import re
import sys
from pathlib import Path
from urllib.parse import urljoin

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://houseduck.in"

# (entry page, English source, {language: document}, section to jump to)
ENTRIES = [
    ("privacy/index.html", "privacy/en.html", {"ko": "/privacy/ko.html", "de": "/privacy/de.html"}, ""),
    ("quirky-ball/privacy/index.html", "privacy/en.html", {"ko": "/privacy/ko.html", "de": "/privacy/de.html"}, ""),
    ("10key/privacy/index.html", "privacy/en.html", {"ko": "/privacy/ko.html", "de": "/privacy/de.html"}, "section-13"),
    ("quirky-ball/terms/index.html", "quirky-ball/terms/en.html",
     {"ko": "/quirky-ball/terms/ko.html", "de": "/quirky-ball/terms/de.html"}, ""),
    ("10key/terms/index.html", "10key/terms/en.html", {"ko": "/10key/terms/ko.html"}, ""),
    ("hexaworld1984/privacy/index.html", "hexaworld1984/privacy/en.html", {"ko": "/hexaworld1984/privacy/ko.html"}, ""),
    ("hexaworld1984/terms/index.html", "hexaworld1984/terms/en.html", {"ko": "/hexaworld1984/terms/ko.html"}, ""),
]

URL_ATTRIBUTE = re.compile(r'\b(href|src)="([^"]*)"')
LANGUAGE_NAV = re.compile(r'<nav class="language-switcher".*?</nav>', re.S)


def absolute(source, value):
    """Relative links of the source document still point to the same place from the entry page's folder."""
    if not value or value.startswith(("/", "#", "http:", "https:", "mailto:", "tel:", "data:")):
        return value
    return urljoin(f"{SITE}/{source}", value)[len(SITE):]


def language_script(languages, section):
    hash_expression = f'(location.hash || "#{section}")' if section else "location.hash"
    rules = "\n".join(
        f'      if (/^{code}(?:[-_]|$)/.test(code)) {{ location.replace("{target}" + {hash_expression}); return; }}'
        for code, target in languages.items()
    )
    jump = ""
    if section:
        jump = (
            '\n  if (!location.hash) document.addEventListener("DOMContentLoaded", function () {\n'
            f'    var target = document.getElementById("{section}");\n'
            f'    if (target) {{ history.replaceState(null, "", "#{section}"); target.scrollIntoView(); }}\n'
            "  });"
        )
    return f"""<script>
// 언어 자동 이동: 이 주소는 영어 문서 전문을 그대로 보여 준다. 브라우저/기기 언어 목록에서 한국어(ko) 또는
// 독일어(de, 그 문서가 있을 때)가 영어(en)보다 먼저 나오면 그 언어 문서로 옮기고, 그 밖에는(일본어 포함) 영어에 머문다.
// ?stay=1 이면 이동하지 않는다.
(function () {{
  try {{
    if (/[?&]stay=1/.test(location.search)) return;
    var langs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || ""];
    for (var i = 0; i < langs.length; i++) {{
      var code = String(langs[i]).toLowerCase();
{rules}
      if (/^en(?:[-_]|$)/.test(code)) break;
    }}
  }} catch (e) {{ /* 영어 문서에 머문다 */ }}{jump}
}})();
</script>"""


def build(entry, source, languages, section):
    html = (ROOT / source).read_text(encoding="utf-8")
    html = URL_ATTRIBUTE.sub(lambda match: f'{match.group(1)}="{absolute(source, match.group(2))}"', html)
    html = re.sub(r'<a class="language-all"[^>]*>.*?</a>', "", html)
    if section:
        html = LANGUAGE_NAV.sub(
            lambda match: re.sub(r'href="(/[^"#]+\.html)"', rf'href="\1#{section}"', match.group(0)), html, count=1)
    html = re.sub(r'\s*<link rel="canonical"[^>]*>', "", html)
    head = (
        f"  <!-- Generated by scripts/build_legal_entry_pages.py from /{source}; edit that file, not this one. -->\n"
        f'  <link rel="canonical" href="{SITE}/{source}">\n'
        f"{language_script(languages, section)}\n"
    )
    if html.count("</head>") != 1:
        raise SystemExit(f"{source}: expected exactly one </head>")
    return html.replace("</head>", head + "</head>")


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for entry, source, languages, section in ENTRIES:
        expected = build(entry, source, languages, section)
        path = ROOT / entry
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == expected:
            continue
        if check:
            stale.append(entry)
        else:
            path.write_text(expected, encoding="utf-8")
            print(f"wrote {entry} from {source}")
    if stale:
        print("legal entry pages out of date with their English source (run scripts/build_legal_entry_pages.py): "
              + ", ".join(stale), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
